"""
Download Firefox's preloaded intermediate certificates into
src/trust/data/mozilla-intermediates.pem.

Firefox gets these certificates from the "security-state/intermediates"
Remote Settings collection, which Mozilla fills from CCADB. It uses them to
complete chains when a server leaves out an intermediate, instead of fetching
the issuer through AIA. cert-info uses the same list so that its chains match
the ones Firefox shows.

Every attachment is checked against the SHA-256 published in its record.

Usage:
    python scripts/update_mozilla_intermediates.py [output.pem]
"""

import base64
import hashlib
import io
import os
import sys
import zipfile
from datetime import datetime, timezone

import requests
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization

SETTINGS_URL = "https://firefox.settings.services.mozilla.com/v1"
CHANGESET_URL = SETTINGS_URL + "/buckets/security-state/collections/intermediates/changeset?_expected=0"
BUNDLE_PATH = "bundles/security-state--intermediates.zip"
DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "trust", "data", "mozilla-intermediates.pem"
)


def main(output: str) -> None:
    """Download, verify and write the preloaded intermediates."""
    server = requests.get(SETTINGS_URL + "/", timeout=60).json()
    base_url = server["capabilities"]["attachments"]["base_url"]
    changeset = requests.get(CHANGESET_URL, timeout=120).json()
    records = [r for r in changeset["changes"] if "attachment" in r and not r.get("deleted")]

    # All attachments in one download; fall back to single files if needed
    bundle = None
    response = requests.get(base_url + BUNDLE_PATH, timeout=300)
    if response.status_code == 200:
        bundle = zipfile.ZipFile(io.BytesIO(response.content))
    names = set(bundle.namelist()) if bundle else set()

    certs = {}
    for record in records:
        attachment = record["attachment"]
        if record["id"] in names:
            data = bundle.read(record["id"])
        else:
            data = requests.get(base_url + attachment["location"], timeout=60).content
        if hashlib.sha256(data).hexdigest() != attachment["hash"]:
            raise SystemExit(f"Attachment hash mismatch for record {record['id']}")
        cert = x509.load_pem_x509_certificate(data)
        der_hash = base64.b64encode(cert.fingerprint(hashes.SHA256())).decode()
        if record.get("derHash") and record["derHash"] != der_hash:
            raise SystemExit(f"Certificate hash mismatch for record {record['id']}")
        certs[der_hash] = cert

    published = datetime.fromtimestamp(changeset["timestamp"] / 1000, timezone.utc)
    lines = [
        "##",
        "## Firefox preloaded intermediate certificates",
        "##",
        f"## Source: {CHANGESET_URL}",
        f"## Collection timestamp: {published:%Y-%m-%d %H:%M:%S} UTC",
        f"## Certificates: {len(certs)}",
        "##",
        "## Generated by scripts/update_mozilla_intermediates.py. Do not edit.",
        "##",
        "",
    ]
    for cert in sorted(certs.values(), key=lambda c: (c.subject.rfc4514_string(), c.fingerprint(hashes.SHA256()))):
        lines.append(f"# {cert.subject.rfc4514_string()}")
        lines.append(cert.public_bytes(serialization.Encoding.PEM).decode().strip())
        lines.append("")
    with open(output, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    print(f"Wrote {len(certs)} certificates to {output}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUTPUT)
