"""
Generate the Mozilla root store from Mozilla's certdata.txt:

    src/trust/data/mozilla-certs.pem       roots Firefox trusts for websites
    src/trust/data/mozilla-distrust.csv    roots whose trust for websites ends for
                                certificates issued after a date
                                (CKA_NSS_SERVER_DISTRUST_AFTER)

certdata.txt is taken from the Firefox release branch, the same source as the
EV root list (scripts/update_firefox_ev_roots.py), so both match the current
Firefox release. A root is included if its trust object marks it as a trusted
issuer for TLS servers (CKA_TRUST_SERVER_AUTH CKT_NSS_TRUSTED_DELEGATOR), as
Firefox does.

Usage:
    python scripts/update_mozilla_roots.py [roots.pem] [distrust.csv]
"""

import csv
import hashlib
import os
import sys
from datetime import datetime, timezone

import requests
from cryptography import x509
from cryptography.hazmat.primitives import serialization

SOURCE_URL = ("https://raw.githubusercontent.com/mozilla-firefox/firefox/refs/heads/release/"
              "security/nss/lib/ckfw/builtins/certdata.txt")
DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "trust", "data")
DEFAULT_ROOTS = os.path.join(DATA_DIR, "mozilla-certs.pem")
DEFAULT_DISTRUST = os.path.join(DATA_DIR, "mozilla-distrust.csv")


def parse_objects(text: str) -> list:
    """Parse certdata.txt into a list of {attribute: value} objects."""
    objects, current = [], None
    lines = iter(text.splitlines())
    for line in lines:
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 2)
        if parts[0] == "CKA_CLASS":
            current = {}
            objects.append(current)
        if current is None or not parts[0].startswith("CKA_"):
            continue
        name, kind = parts[0], parts[1] if len(parts) > 1 else ""
        if kind == "MULTILINE_OCTAL":
            data = bytearray()
            for octal_line in lines:
                if octal_line.strip() == "END":
                    break
                data.extend(int(octet, 8) for octet in octal_line.strip().split("\\")[1:])
            current[name] = bytes(data)
        else:
            current[name] = parts[2] if len(parts) > 2 else ""
    return objects


def roots_and_distrust(text: str) -> tuple:
    """(list of trusted root certificates, {sha256 hex: distrust-after datetime})."""
    objects = parse_objects(text)
    certificates = {}
    for obj in objects:
        if obj.get("CKA_CLASS") == "CKO_CERTIFICATE":
            der = obj["CKA_VALUE"]
            certificates[hashlib.sha1(der).digest()] = obj
    roots, distrust = [], {}
    for obj in objects:
        if obj.get("CKA_CLASS") != "CKO_NSS_TRUST":
            continue
        if obj.get("CKA_TRUST_SERVER_AUTH") != "CKT_NSS_TRUSTED_DELEGATOR":
            continue
        cert_obj = certificates.get(obj["CKA_CERT_SHA1_HASH"])
        if cert_obj is None:
            raise SystemExit("Trust object without a matching certificate")
        cert = x509.load_der_x509_certificate(cert_obj["CKA_VALUE"])
        roots.append(cert)
        distrust_after = cert_obj.get("CKA_NSS_SERVER_DISTRUST_AFTER")
        if isinstance(distrust_after, bytes):
            # UTCTime, e.g. b"241130235959Z"
            date = datetime.strptime(distrust_after.decode(), "%y%m%d%H%M%SZ").replace(tzinfo=timezone.utc)
            distrust[hashlib.sha256(cert_obj["CKA_VALUE"]).hexdigest()] = (date, cert)
    if not roots:
        raise SystemExit("No trusted roots found; the certdata.txt format may have changed")
    return roots, distrust


def main(roots_path: str, distrust_path: str) -> None:
    response = requests.get(SOURCE_URL, timeout=120)
    response.raise_for_status()
    roots, distrust = roots_and_distrust(response.text)
    generated = datetime.now(timezone.utc)
    lines = [
        "##",
        "## Mozilla root store: roots Firefox trusts for websites",
        "##",
        f"## Source: {SOURCE_URL}",
        f"## Generated: {generated:%Y-%m-%d %H:%M:%S} UTC",
        f"## Certificates: {len(roots)}",
        "##",
        "## Generated by scripts/update_mozilla_roots.py. Do not edit.",
        "##",
        "",
    ]
    for cert in sorted(roots, key=lambda c: c.subject.rfc4514_string()):
        lines.append(f"# {cert.subject.rfc4514_string()}")
        lines.append(cert.public_bytes(serialization.Encoding.PEM).decode().strip())
        lines.append("")
    with open(roots_path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    with open(distrust_path, "w", newline="", encoding="utf-8") as out:
        writer = csv.writer(out)
        writer.writerow(["sha256_fingerprint", "distrust_after", "root_subject"])
        for fingerprint, (date, cert) in sorted(distrust.items(), key=lambda item: item[1][0]):
            writer.writerow([fingerprint, date.strftime("%Y-%m-%dT%H:%M:%SZ"), cert.subject.rfc4514_string()])
    print(f"Wrote {len(roots)} roots to {roots_path} and {len(distrust)} distrust dates to {distrust_path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ROOTS,
         sys.argv[2] if len(sys.argv) > 2 else DEFAULT_DISTRUST)
