"""
Mozilla trust data: the files in src/trust/data and their loaders.

    mozilla-certs.pem           roots Firefox trusts for websites
    mozilla-distrust.csv        roots' distrust dates for websites
    mozilla-intermediates.pem   Firefox's preloaded intermediates
    firefox-ev-roots.csv        roots Firefox trusts for each EV policy
    mozilla-onecrl.json         OneCRL: revoked CA certificates
    firefox-ct-logs.json        Certificate Transparency logs Firefox knows
    firefox-pins.json           Firefox's static public key pins

The files are generated by scripts/update_trust_data.py.
"""

import base64
import csv
import json
import os
import re
import warnings
from dataclasses import dataclass, field
from datetime import datetime, timezone

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.utils import CryptographyDeprecationWarning

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
MOZILLA_ROOTS = os.path.join(DATA_DIR, "mozilla-certs.pem")
MOZILLA_DISTRUST = os.path.join(DATA_DIR, "mozilla-distrust.csv")
MOZILLA_INTERMEDIATES = os.path.join(DATA_DIR, "mozilla-intermediates.pem")
FIREFOX_EV_ROOTS = os.path.join(DATA_DIR, "firefox-ev-roots.csv")
MOZILLA_ONECRL = os.path.join(DATA_DIR, "mozilla-onecrl.json")
FIREFOX_CT_LOGS = os.path.join(DATA_DIR, "firefox-ct-logs.json")
FIREFOX_PINS = os.path.join(DATA_DIR, "firefox-pins.json")

_PEM_RE = re.compile(rb"-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----", re.S)


def _parse_time(value: str) -> datetime:
    return datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def _load_json(path: str) -> dict | None:
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as json_file:
        return json.load(json_file)


def load_pem_bundle(path: str) -> list:
    """
    Load every certificate from a PEM bundle. Missing files give an empty list.

    Args:
        path (str): Path to the PEM file.

    Returns:
        list: The x509.Certificate objects in the file.
    """
    if not os.path.isfile(path):
        return []
    with open(path, "rb") as bundle:
        data = bundle.read()
    return load_pem_certificates(data)


def load_pem_certificates(data: bytes) -> list:
    """
    Parse every PEM certificate found in a byte string, skipping invalid ones.

    Args:
        data (bytes): Data containing one or more PEM certificates.

    Returns:
        list: The x509.Certificate objects.
    """
    certs = []
    for block in _PEM_RE.findall(data):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", CryptographyDeprecationWarning)
                certs.append(x509.load_pem_x509_certificate(block))
        except ValueError:
            continue
    return certs


def load_ev_roots(path: str) -> dict:
    """
    Firefox's EV roots: SHA-256 fingerprint (hex) -> set of policy OIDs the
    root is registered for. Missing files give an empty dict (no EV).
    """
    ev_roots = {}
    if not os.path.isfile(path):
        return ev_roots
    with open(path, newline="", encoding="utf-8") as ev_file:
        for row in csv.DictReader(ev_file):
            ev_roots.setdefault(row["sha256_fingerprint"].lower(), set()).add(row["policy_oid"])
    return ev_roots


def load_distrust(path: str) -> dict:
    """Roots' distrust dates: SHA-256 fingerprint (hex) -> datetime."""
    distrust = {}
    if not os.path.isfile(path):
        return distrust
    with open(path, newline="", encoding="utf-8") as distrust_file:
        for row in csv.DictReader(distrust_file):
            distrust[row["sha256_fingerprint"].lower()] = _parse_time(row["distrust_after"])
    return distrust


class OneCRL:
    """Mozilla's list of revoked CA certificates (see scripts/update_mozilla_onecrl.py)."""

    def __init__(self, issuer_serial=(), subject_pubkey_hash=()):
        self._issuer_serial = {(base64.b64decode(i), base64.b64decode(s)) for i, s in issuer_serial}
        self._subject_key = {(base64.b64decode(s), base64.b64decode(k)) for s, k in subject_pubkey_hash}

    @classmethod
    def load(cls, path: str) -> "OneCRL":
        if not os.path.isfile(path):
            return cls()
        with open(path, encoding="utf-8") as onecrl_file:
            data = json.load(onecrl_file)
        return cls(data.get("issuer_serial", []), data.get("subject_pubkey_hash", []))

    def __len__(self):
        return len(self._issuer_serial) + len(self._subject_key)

    def revokes(self, cert: x509.Certificate) -> bool:
        """Whether the certificate is listed, by issuer and serial or by subject and key."""
        if not self:
            return False
        serial = cert.serial_number
        serial_bytes = serial.to_bytes((serial.bit_length() + 8) // 8, "big", signed=True)
        if (cert.issuer.public_bytes(), serial_bytes) in self._issuer_serial:
            return True
        try:
            spki = cert.public_key().public_bytes(serialization.Encoding.DER,
                                                  serialization.PublicFormat.SubjectPublicKeyInfo)
        except Exception:
            return False
        key_hash = hashes.Hash(hashes.SHA256())
        key_hash.update(spki)
        return (cert.subject.public_bytes(), key_hash.finalize()) in self._subject_key


@dataclass(frozen=True)
class CTLog:
    """A Certificate Transparency log, as listed in Firefox (CTKnownLogs.h)."""
    name: str
    log_id: bytes
    admissible: bool        # False: retired
    tiled: bool             # static-ct-api log: SCTs must carry a leaf index
    timestamp: datetime     # for a retired log, when it was retired
    operator_id: int
    key: bytes              # DER SubjectPublicKeyInfo


@dataclass
class CTLogList:
    """Firefox's CT logs and the time after which Firefox stops enforcing CT."""
    logs: dict = field(default_factory=dict)    # log ID -> CTLog
    expiration: datetime | None = None

    @classmethod
    def load(cls, path: str) -> "CTLogList":
        data = _load_json(path)
        if not data:
            return cls()
        logs = {}
        for entry in data["logs"]:
            log = CTLog(
                name=entry["name"], log_id=base64.b64decode(entry["log_id"]),
                admissible=entry["state"] == "Admissible", tiled=entry["format"] == "Tiled",
                timestamp=datetime.fromtimestamp(entry["timestamp_ms"] / 1000, timezone.utc),
                operator_id=entry["operator_id"], key=base64.b64decode(entry["key"]))
            logs[log.log_id] = log
        return cls(logs, _parse_time(data["expiration"]))


@dataclass
class StaticPins:
    """Firefox's static public key pins (StaticHPKPins.h)."""
    entries: dict = field(default_factory=dict)   # host -> (include_subdomains, test_mode, {sha256 SPKI})
    expiration: datetime | None = None

    @classmethod
    def load(cls, path: str) -> "StaticPins":
        data = _load_json(path)
        if not data:
            return cls()
        pinsets = {name: {base64.b64decode(h) for h in hashes_} for name, hashes_ in data["pinsets"].items()}
        entries = {
            entry["host"]: (entry["include_subdomains"], entry["test_mode"], pinsets[entry["pinset"]])
            for entry in data["entries"] if entry["pinset"]
        }
        return cls(entries, _parse_time(data["expiration"]))


@dataclass
class TrustStore:
    """All the trust data Firefox uses to build and accept chains."""
    roots: list = field(default_factory=list)
    intermediates: list = field(default_factory=list)
    ev_roots: dict = field(default_factory=dict)
    distrust: dict = field(default_factory=dict)
    onecrl: OneCRL = field(default_factory=OneCRL)
    ct_logs: CTLogList = field(default_factory=CTLogList)
    pins: StaticPins = field(default_factory=StaticPins)

    _mozilla = None

    @classmethod
    def mozilla(cls) -> "TrustStore":
        """The bundled Mozilla trust data, read once per process."""
        if cls._mozilla is None:
            cls._mozilla = cls(
                roots=load_pem_bundle(MOZILLA_ROOTS),
                intermediates=load_pem_bundle(MOZILLA_INTERMEDIATES),
                ev_roots=load_ev_roots(FIREFOX_EV_ROOTS),
                distrust=load_distrust(MOZILLA_DISTRUST),
                onecrl=OneCRL.load(MOZILLA_ONECRL),
                ct_logs=CTLogList.load(FIREFOX_CT_LOGS),
                pins=StaticPins.load(FIREFOX_PINS),
            )
            if not cls._mozilla.intermediates:
                print(f"Warning: '{MOZILLA_INTERMEDIATES}' not found or empty; "
                      "chains will not be completed with Firefox's preloaded intermediates.")
        return cls._mozilla
